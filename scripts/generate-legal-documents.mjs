import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const VERSION = "beta-2026-08-04";
const source = `legal/${VERSION}/terms.md`;
const bytes = readFileSync(source);
const sha256 = createHash("sha256").update(bytes).digest("hex");
const content = bytes.toString("utf8");

const summary =
  "You must be 18 or older. There is no tolerance for objectionable content or abusive behaviour, every Moment and profile can be reported or blocked, and section 8 explains what Splotty collects, who processes it, and how long it is kept.";

const module = `export const LEGAL_DOCUMENT_VERSION = ${JSON.stringify(VERSION)};

/**
 * One document, one acceptance. The 18-and-over rule, the acceptable-use rules,
 * and the privacy notice are sections of the terms rather than four separate
 * agreements, so onboarding asks once.
 *
 * \`content\` is the exact UTF-8 text of \`${source}\`, bundled so the
 * agreement is readable offline and before a session exists. \`sha256\` is its
 * digest; the same version/hash pair is stored in \`private.legal_documents\`,
 * checked by \`npm run legal:check\`, and asserted by pgTAP. A test in this
 * folder re-hashes \`content\` against the file, so the three can never drift.
 *
 * Generated by \`npm run legal:generate\` — do not hand-edit. Publish a
 * replacement by adding a new \`legal/<version>/\` directory, pointing the
 * generator at it, and writing the new version/hash into a migration.
 */
export const LEGAL_DOCUMENT = {
  kind: "terms",
  title: "Terms of Use and Privacy Notice",
  sha256: ${JSON.stringify(sha256)},
  /** The one-line promise the single acceptance control is attached to. */
  summary: ${JSON.stringify(summary)},
  content: ${JSON.stringify(content)},
} as const;

type LegalAcceptanceReference = {
  content_sha256: string;
  document_kind: string;
  document_version: string;
};

/**
 * True when the caller has accepted exactly the document this build ships.
 * A new version or a changed hash makes every prior acceptance stale, which is
 * what forces re-acceptance through onboarding.
 */
export function hasCurrentAcceptance(acceptances: LegalAcceptanceReference[]) {
  return acceptances.some(
    (acceptance) =>
      acceptance.document_kind === LEGAL_DOCUMENT.kind &&
      acceptance.document_version === LEGAL_DOCUMENT_VERSION &&
      acceptance.content_sha256 === LEGAL_DOCUMENT.sha256,
  );
}
`;

writeFileSync("src/features/legal/legal-documents.ts", module);
console.log(`wrote legal-documents.ts for ${VERSION} (${sha256})`);
